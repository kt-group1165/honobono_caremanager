/** 字形の異体字だけを寄せる (別姓の可能性がある齋/齊は含めない) */
export const ITAIJI = {
  "髙": "高", "﨑": "崎", "濵": "浜", "邉": "辺", "邊": "辺",
  "冨": "富", "廣": "広", "德": "徳", "惠": "恵", "愼": "慎", "淸": "清", "眞": "真",
  "瀨": "瀬", "栁": "柳", "槗": "橋", "曻": "昇", "澤": "沢",
  "淺": "浅", // 2026-09-14 モニタリングPDF (淺井珠惠) で発見・追加
};

/**
 * 氏名の正規化 (NFKC + 空白除去 + 異体字を寄せる)。
 * 利用者の同定 (事業所+氏名) に使う。
 */
export function normName(v) {
  return String(v ?? "")
    .normalize("NFKC")
    .replace(/[\s　]/g, "")
    .replace(/./g, (ch) => ITAIJI[ch] ?? ch)
    .trim();
}
