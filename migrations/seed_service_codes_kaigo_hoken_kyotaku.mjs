async function main() {
  console.log(`\n📂 介護保険 居宅サービス baseline seed (令和6年報酬改定)`);
  console.log(`   総 ${rows.length} 件`);
  // category 別内訳
  const catCount = {};
  for (const r of rows) catCount[r.service_category] = (catCount[r.service_category] ?? 0) + 1;
  for (const [k, v] of Object.entries(catCount).sort()) {
    const nm = rows.find(r => r.service_category === k)?.service_category_name ?? "";
    console.log(`   ${k.padEnd(4)} ${nm.padEnd(30)} ${v} 件`);
  }
  console.log(EXECUTE ? "\n⚠️  EXECUTE MODE (INSERT)" : "\n🔍 DRY RUN");

  // 既存 check (system, service_code, valid_from) の 3 列複合
  const codes = rows.map(r => r.service_code);
  // 100 件ごとに in() query (URL 長さ回避)
  const existingSet = new Set();
  for (let i = 0; i < codes.length; i += 100) {
    const slice = codes.slice(i, i + 100);
    const { data, error } = await sb.from("kaigo_service_codes")
      .select("service_code, system, valid_from")
      .eq("system", "介護")
      .in("service_code", slice);
    if (error) { console.error("check failed:", error.message); process.exit(1); }
    for (const e of (data ?? [])) existingSet.add(`${e.system}::${e.service_code}::${e.valid_from}`);
  }
  const toInsert = rows.filter(r => !existingSet.has(`${r.system}::${r.service_code}::${r.valid_from}`));
  console.log(`\n  新規 ${toInsert.length} / 既存 skip ${rows.length - toInsert.length}`);

  if (!EXECUTE) { console.log("\n(DRY RUN 完了。 --execute で本番投入)"); return; }
  if (toInsert.length === 0) { console.log("既に投入済 → 何もしない"); return; }

  const chunk = 100;
  let inserted = 0;
  for (let i = 0; i < toInsert.length; i += chunk) {
    const slice = toInsert.slice(i, i + chunk);
    const { error } = await sb.from("kaigo_service_codes").insert(slice);
    if (error) {
      console.error(`INSERT 失敗 (chunk ${i}-${i + slice.length}):`, error.message);
      process.exit(1);
    }
    inserted += slice.length;
    console.log(`  ✅ ${inserted}/${toInsert.length}`);
  }
  console.log(`\n完了。新規 ${inserted} 件 INSERT`);
}

main().catch(e => { console.error(e); process.exit(1); });
