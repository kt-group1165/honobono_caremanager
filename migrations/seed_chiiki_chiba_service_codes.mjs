// ── 行の組み立て ─────────────────────────────────────────────────────────────
function buildRows() {
  const rows = [];
  const push = (code, name, units, calcType, unitType, extraNote) => {
    const category = code.slice(0, 2);
    rows.push({
      system: SYSTEM,
      municipality: MUNICIPALITY,
      service_category: category,
      service_category_name: category === "02" ? "移動支援" : "訪問入浴サービス",
      service_code: code,
      service_name: name,
      short_name: name,
      units,
      unit_type: unitType,
      calculation_type: calcType,
      valid_from: VALID_FROM,
      valid_until: null,
      notes: extraNote ? `${NOTES} / ${extraNote}` : NOTES,
    });
  };

  // 単一時間帯 + 増分 (生成 + anchor 検算)
  for (const def of SINGLE_SERIES) {
    for (const [code, name, units] of series(def)) {
      const anchor = SERIES_ANCHORS[code];
      if (anchor !== undefined && anchor !== units) {
        throw new Error(`検算不一致: ${code} 生成=${units} コード表=${anchor}`);
      }
      push(code, name, units, "基本", "1回につき", null);
    }
  }
  // 複合 (2人ペア展開)
  for (const [start, name, units] of COMBO) {
    push(c6(start), name, units, "基本", "1回につき", "複合時間帯");
    push(c6(start + 1), `${name}・2人`, units, "基本", "1回につき", "複合時間帯");
  }
  // 加算・訪問入浴
  for (const [code, name, units, calcType, unitType, note] of IDOU_KASAN) push(code, name, units, calcType, unitType, note);
  for (const [code, name, units, calcType, unitType, note] of BATH) push(code, name, units, calcType, unitType, note);

  // 整合性チェック: コード重複なし
  const seen = new Set();
  for (const r of rows) {
    if (seen.has(r.service_code)) throw new Error(`コード重複: ${r.service_code}`);
    seen.add(r.service_code);
  }
  return rows;
}

// ── REST helper ──────────────────────────────────────────────────────────────
async function rest(path, opts = {}) {
  const res = await fetch(`${SB_URL}/rest/v1/${path}`, {
    ...opts,
    headers: {
      apikey: SB_KEY,
      Authorization: `Bearer ${SB_KEY}`,
      "Content-Type": "application/json",
      ...(opts.headers ?? {}),
    },
  });
  return res;
}

async function countExisting() {
  const res = await rest(
    `kaigo_service_codes?system=eq.${encodeURIComponent(SYSTEM)}&valid_from=eq.${VALID_FROM}&select=id`,
    { headers: { Prefer: "count=exact", Range: "0-0" } },
  );
  const cr = res.headers.get("content-range");
  return cr ? Number(cr.split("/")[1]) : 0;
}

// ── main ─────────────────────────────────────────────────────────────────────
async function main() {
  const rows = buildRows();

  const byCat = {};
  for (const r of rows) byCat[`${r.service_category} ${r.service_category_name}`] = (byCat[`${r.service_category} ${r.service_category_name}`] ?? 0) + 1;
  console.log(`千葉市地域生活支援給付 コード生成: 合計 ${rows.length} 件 (検算OK)`);
  for (const [k, v] of Object.entries(byCat)) console.log(`  ${k}: ${v} 件`);

  const existing = await countExisting();
  if (existing > 0) {
    console.error(`\n中止: system='${SYSTEM}' valid_from=${VALID_FROM} が既に ${existing} 件あります (二重投入防止)`);
    console.error(`やり直す場合は先に削除:`);
    console.error(`  DELETE FROM kaigo_service_codes WHERE system='${SYSTEM}' AND valid_from='${VALID_FROM}';`);
    process.exit(2);
  }

  if (!EXECUTE) {
    console.log("\n--- DRY RUN (先頭 10 件) ---");
    for (const r of rows.slice(0, 10)) console.log(`  ${r.service_code} ${r.service_name} ${r.units}単位 [${r.calculation_type}/${r.unit_type}]`);
    console.log(`  ... 他 ${rows.length - 10} 件`);
    console.log("\n本実行: node migrations/seed_chiiki_chiba_service_codes.mjs --execute");
    return;
  }

  console.log("\nINSERT 実行中...");
  for (let i = 0; i < rows.length; i += BATCH) {
    const chunk = rows.slice(i, i + BATCH);
    const res = await rest("kaigo_service_codes", {
      method: "POST",
      headers: { Prefer: "return=minimal" },
      body: JSON.stringify(chunk),
    });
    if (!res.ok) {
      console.error(`INSERT 失敗 (batch ${i / BATCH + 1}): ${res.status} ${await res.text()}`);
      process.exit(1);
    }
    console.log(`  batch ${i / BATCH + 1}: ${chunk.length} 件 OK`);
  }

  // 件数確認 (必須: silent failure 防止)
  const after = await countExisting();
  if (after === rows.length) {
    console.log(`\n完了: ${after} 件 INSERT 済み (期待値と一致)`);
  } else {
    console.error(`\n警告: DB 件数 ${after} ≠ 期待 ${rows.length}。確認してください`);
    process.exit(1);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
