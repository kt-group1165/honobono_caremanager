/** 単一時間帯 / 増分の系列を生成 (コードは 4 刻み、+1 が「・2人」) */
function series({ start, prefix, band, base, mult, count, zobun = false }) {
  const rows = [];
  for (let i = 0; i < count; i++) {
    const units = round(base[i] * mult);
    const name = `${prefix}${band}${zobun ? "増" : ""}${hh(i)}`;
    const code = start + i * 4;
    rows.push([c6(code), name, units]);
    rows.push([c6(code + 1), `${name}・2人`, units]);
  }
  return rows;
}

