/**
 * 拠点フォルダ名 → その拠点の offices 行。
 * @param area    拠点フォルダ名 ("K姉" 等)
 * @param offices offices の配列 (id, name, service_type)
 */
export function officesForArea(area, offices) {
  const want = AREA_OFFICES[area];
  if (!want) return [];
  if (want === ALL_KYOTAKU) return offices.filter((o) => o.service_type === "居宅介護支援");
  const norm = (v) => String(v ?? "").normalize("NFKC").replace(/[\s　]/g, "");
  return offices.filter((o) => want.some((w) => norm(o.name).startsWith(norm(w))));
}

