// 障害 本体 (時間帯 x category)
for (const [svcCat, catNum, subCat, codePrefix, timeBrackets] of SHOGAI_BASE) {
  timeBrackets.forEach(([tb, base], tbIdx) => {
    for (const t of TIME_MULTIPLIERS) {
      const units = Math.round(base * t.mult);
      const nameSuffix = t.key === "日" ? "" : `・${t.key}間`;
      const codeSuffix = String(tbIdx + 1).padStart(2, "0");
      const code = `${codePrefix}${codeSuffix}${t.suffix}`;
      const name = subCat
        ? `${svcCat} ${subCat} ${tb}${nameSuffix}`
        : `${svcCat} ${tb}${nameSuffix}`;
      rows.push({
        system: "障害",
        service_category: catNum,
        service_category_name: svcCat,
        service_code: code,
        service_name: name,
        units,
        unit_type: "1回につき",
        calculation_type: "基本",
        valid_from: V,
        valid_until: null,
        notes: `令和6年報酬改定 / ${t.key}間帯${t.mult !== 1 ? ` (x${t.mult})` : ""}`,
      });
    }
  });
}

