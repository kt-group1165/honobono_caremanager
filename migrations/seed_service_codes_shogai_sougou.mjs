async function main() {
  console.log(`\n📂 サービスコード baseline seed (障害訪問系 + 総合事業)`);
  console.log(`   総 ${rows.length} 件`);
  console.log(`   - 障害 本体+時間帯: ${rows.filter(r => r.system==="障害" && r.calculation_type==="基本").length}`);
  console.log(`   - 障害 加算:        ${rows.filter(r => r.system==="障害" && r.calculation_type==="加算").length}`);
  console.log(`   - 総合事業:         ${rows.filter(r => r.system==="総合事業").length}`);
  console.log(EXECUTE ? "⚠️  EXECUTE MODE (upsert)" : "🔍 DRY RUN");

  // 既存 code check
  const codes = rows.map(r => r.service_code);
  const { data: existing } = await sb.from("kaigo_service_codes")
    .select("service_code, system, valid_from").in("service_code", codes);
  const existingSet = new Set((existing ?? []).map(r => `${r.system}::${r.service_code}::${r.valid_from}`));
  const toInsert = rows.filter(r => !existingSet.has(`${r.system}::${r.service_code}::${r.valid_from}`));
  console.log(`  新規 ${toInsert.length} / 既存 skip ${rows.length - toInsert.length}`);

  if (!EXECUTE) { console.log("\n(DRY RUN)"); return; }
  if (toInsert.length === 0) { console.log("既に投入済 → 何もしない"); return; }
  const chunk = 100;
  for (let i = 0; i < toInsert.length; i += chunk) {
    const slice = toInsert.slice(i, i + chunk);
    const { error } = await sb.from("kaigo_service_codes").insert(slice);
    if (error) { console.error("INSERT 失敗:", error.message); process.exit(1); }
    console.log(`  ✅ ${i + slice.length}/${toInsert.length}`);
  }
  console.log("\n完了");
}

main().catch(e => { console.error(e); process.exit(1); });
