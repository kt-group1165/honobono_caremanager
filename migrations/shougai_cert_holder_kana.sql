-- 障害児の「支給決定者 (保護者) 氏名カナ」を受給者証に持たせる。
--
-- 背景:
--   J121 明細書 基本情報レコードは
--     項8 支給決定者氏名カナ / 項9 支給決定児童氏名カナ
--   の 2 枠を持つ。成人は 項8=本人・項9=空 だが、**障害児は 項8=保護者・項9=児童**。
--   ほのぼの KJ260701 (茂原 2026-06) では
--     狩野 1242311080: 項8=ｶﾉﾖｼﾕｷ (保護者) / 項9=ｶﾉﾕｳｶ (児童)
--     鈴木 1242241337: 項8=ｽｽﾞｷﾏﾘ (保護者) / 項9=ｽｽﾞｷｱｵｲ (児童)
--   となっており、新システムは本人カナを 項8 に出していて不一致だった。
--
-- 設計:
--   保護者は「その受給者証の支給決定者」なので clients ではなく受給者証に持たせる。
--   NULL = 成人 (項8=本人カナ / 項9=空)。
--   値あり = 障害児 (項8=この値 / 項9=本人カナ)。
--
-- Supabase SQL Editor に **このブロックごと** 貼って Run すること
-- (BEGIN だけで COMMIT を忘れると実行終了時に auto rollback される)。

BEGIN;

ALTER TABLE shougai_certifications
  ADD COLUMN IF NOT EXISTS holder_name_kana text;

COMMENT ON COLUMN shougai_certifications.holder_name_kana IS
  '支給決定者(保護者)氏名カナ。障害児のみ設定し、成人は NULL。'
  'J121 明細書 項8 に出力し、設定時は 項9 に本人カナを出す。';

COMMIT;
