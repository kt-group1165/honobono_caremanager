async function main() {
  console.log(`📂 契約書兼重要事項説明書 template v1 seed`);
  console.log(`   keys=${Object.keys(V1_CONTENT).length}`);
  console.log(EXECUTE ? "⚠️  EXECUTE MODE" : "🔍 DRY RUN");

  // 既存 v1 が居るか
  const { data: existing, error: e0 } = await sb
    .from("kaigo_contract_templates")
    .select("id, version_no, is_active")
    .eq("kind", "契約書兼重要事項説明書")
    .eq("version_no", 1)
    .maybeSingle();
  if (e0) {
    console.error("❌ SELECT 失敗:", e0.message);
    process.exit(1);
  }
  if (existing) {
    console.log(`ℹ️  既に v1 存在 (id=${existing.id}, is_active=${existing.is_active})。skip.`);
    process.exit(0);
  }

  if (!EXECUTE) {
    console.log(`(DRY RUN) INSERT する予定: kind=契約書兼重要事項説明書 v1 is_active=true`);
    process.exit(0);
  }

  const { error: eIns } = await sb.from("kaigo_contract_templates").insert({
    kind: "契約書兼重要事項説明書",
    version_no: 1,
    effective_from: new Date().toISOString().slice(0, 10),
    is_active: true,
    content: V1_CONTENT,
    notes: "初版 (docx 原本 = 令和 6 年 6 月版 大網事業所 baseline)",
  });
  if (eIns) {
    console.error("❌ INSERT 失敗:", eIns.message);
    process.exit(1);
  }
  console.log(`✅ v1 INSERT 完了`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
