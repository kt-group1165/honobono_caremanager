// ============================================================================
// ほのぼの稼働データ (MEISAI) の利用者名を clients と突合できる形に正規化する。
//
// ── なぜ要るか ────────────────────────────────────────────────────────
//   ほのぼのは**同じ人を用途ごとに別利用者として登録**するので、氏名の末尾に
//   制度の目印が付く。clients 側は目印なしなので、そのままでは突合できない。
//
//     括弧つき  : 佐藤　あゆみ(障) / 菅原　恵美（支） / 池田　咲子（中央）
//     括弧なし  : 松崎　淑子　移 / 田中　雪江 障 / 高山　光夫　支
//
//   括弧つきは元から落としていたが、**括弧なしを落としていなかった**ため
//   15 名が「氏名一致 0 件」で取り込めていなかった (2026-08-20 発見。
//   障害の突合で「ほのぼのだけに居る」13 名の主因)。
//
// ── 末尾トークンを機械的に落としてはいけない ──────────────────────────
//   外国人の氏名は 3 トークンになることがある (FOO　YUEN　FUN / LEE　SOOG　RYE)。
//   「3 つ目は目印」と決め打つと氏名の一部を削ってしまう。
//   そこで **実データに出た目印だけのホワイトリスト**で落とす。
//   新しい目印が出たら MARKERS に足す (勝手に増やさない)。
// ============================================================================

/** 実データ (93 本の MEISAI / 2,491 名) に出た制度・事業所の目印 */
export const MEISAI_NAME_MARKERS = [
  // 括弧なしで出たもの
  "移", "障", "支", "有",
  // 括弧つきで出たもの (括弧が外れた形で来ても拾えるように)
  "身障", "有料", "同行", "身", "精", "知", "実", "児", "介", "総", "中央",
];

const NORM_BASE = (s) => (s || "").normalize("NFKC").replace(/[\s　]/g, "");

/** 職員名。末尾の「様」を落とす */
export const normStaffName = (s) => NORM_BASE(s).replace(/様$/, "");

/**
 * 利用者名。括弧つきの目印 → 括弧なしの目印 → 空白 の順に落とす。
 * ⚠ 空白を消す前に目印を落とすこと。先に空白を消すと「移」が名前の一部と
 *   区別できなくなる。
 */
export function normClientName(s) {
  let n = (s || "").normalize("NFKC");
  // 1) 末尾の (…) を落とす
  n = n.replace(/[（(][^）)]*[）)]\s*$/, "");
  // 1b) **閉じ括弧が無い**まま切れている分も落とす。氏名欄が欄幅で切れるため
  //     「鈴木　拓也（2人目」「清水　 日出男(障」のように尻切れで来る。
  //     氏名に開き括弧だけが現れることは無いので、開いたまま末尾まで行ったら目印とみなす。
  n = n.replace(/[（(][^）)]*$/, "");
  // 2) 空白で区切られた末尾の目印を落とす (トークンが 3 つ以上のときだけ)
  for (;;) {
    const parts = n.trim().split(/[\s　]+/).filter(Boolean);
    if (parts.length < 3) break;
    if (!MEISAI_NAME_MARKERS.includes(parts[parts.length - 1])) break;
    parts.pop();
    n = parts.join(" ");
  }
  return NORM_BASE(n).replace(/様$/, "");
}
