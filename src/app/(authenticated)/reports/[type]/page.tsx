import Link from "next/link";
import { AlertTriangle, FileText } from "lucide-react";
import { createClient } from "@/lib/supabase/server";
import { UserSidebar } from "@/components/users/user-sidebar";
import { REPORT_CONFIG } from "./report-config";
import {
  ReportsContent,
  type Certification,
  type ReportDoc,
} from "./reports-content";

export default async function ReportTypePage({
  params,
  searchParams,
}: {
  params: Promise<{ type: string }>;
  searchParams: Promise<{ user?: string }>;
}) {
  const [{ type: reportType }, { user: userId }] = await Promise.all([params, searchParams]);
  const config = REPORT_CONFIG[reportType];

  if (!config) {
    return (
      <div className="flex flex-col items-center justify-center py-24 text-gray-500">
        <AlertTriangle size={40} className="mb-3 text-amber-400" />
        <p className="text-lg font-semibold text-gray-700">不明な帳票種別です</p>
        <Link href="/reports" className="mt-4 text-sm text-blue-600 hover:underline">帳票一覧に戻る</Link>
      </div>
    );
  }

  const isCertLinked = ["care-plan-1", "care-plan-2", "care-plan-3", "yobo-care-plan"].includes(reportType);

  let initialDocs: ReportDoc[] = [];
  let initialCertifications: Certification[] = [];

  if (userId) {
    const supabase = await createClient();

    // 並列 fetch: cert と docs を同時取得 (cert なし帳票は cert promise を null で resolve)
    // initialDocs は cert filter が必要ならまず無 filter で全件取って後で client 側 filter
    // するパターンも検討したが、cert link 帳票の最新 cert に絞った docs は server で確定
    // させる方が UI 切替時のチラつきが少ない。
    // → 2段階に分けず: cert fetch を先に await し、docs query は cert に依存させる。
    //   ただし「無ければ autoGenerateDoc」はもう走らせない (client 側 fallback)。
    const certPromise = isCertLinked
      ? supabase
          .from("client_insurance_records")
          .select("id, care_level, start_date:certification_start_date, end_date:certification_end_date")
          .eq("client_id", userId)
          .order("certification_start_date", { ascending: false, nullsFirst: false })
      : null;

    // Cert link でない帳票は docs を即時 parallel fetch
    const docsPromiseNoFilter = !isCertLinked
      ? supabase
          .from("kaigo_report_documents")
          .select("*")
          .eq("user_id", userId)
          .eq("report_type", reportType)
          .order("updated_at", { ascending: false })
      : null;

    if (certPromise && isCertLinked) {
      const { data: certData } = await certPromise;
      initialCertifications = (certData ?? []) as Certification[];
      const initialCertId = initialCertifications[0]?.id ?? null;

      let q = supabase
        .from("kaigo_report_documents")
        .select("*")
        .eq("user_id", userId)
        .eq("report_type", reportType);
      if (initialCertId) q = q.eq("certification_id", initialCertId);
      const { data: docData } = await q.order("updated_at", { ascending: false });
      initialDocs = (docData ?? []) as ReportDoc[];
    } else if (docsPromiseNoFilter) {
      const { data: docData } = await docsPromiseNoFilter;
      initialDocs = (docData ?? []) as ReportDoc[];
    }
    // 既存帳票が無いときの「自動生成」は server 側では走らせない。
    // 理由: autoGenerateDoc は 5+ クエリ + INSERT を含み、user 切替の体感を著しく
    // 悪化させる (= 数百 ms 〜 1 秒)。client 側の useEffect で fallback として
    // 起動し、その間は「読み込み中」表示にする。
  }

  return (
    <div className="flex h-full -m-6">
      <UserSidebar />
      {userId ? (
        <ReportsContent
          userId={userId}
          reportType={reportType}
          initialDocs={initialDocs}
          initialCertifications={initialCertifications}
        />
      ) : (
        <div className="flex-1 overflow-y-auto p-6">
          <div className="flex flex-col items-center justify-center py-24 text-gray-400 no-print">
            <FileText size={48} className="mb-4 text-gray-300" />
            <p className="text-base font-medium">左側のリストから利用者を選択してください</p>
          </div>
        </div>
      )}
    </div>
  );
}
