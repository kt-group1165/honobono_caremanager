/**
 * サービス名から略称を生成。マッチしなければ先頭 3 文字。
 * 空文字は "—"。
 */
export function serviceShortName(name: string | null | undefined): string {
  if (!name) return "—";
  const trimmed = name.trim();
  if (!trimmed) return "—";
  for (const rule of RULES) {
    const m = trimmed.match(rule.re);
    if (m) return rule.out(m, trimmed);
  }
  return trimmed.slice(0, 3);
}
