const Z2A: Record<string, string> = {
  "０": "0", "１": "1", "２": "2", "３": "3", "４": "4",
  "５": "5", "６": "6", "７": "7", "８": "8", "９": "9",
};
const zenkakuToAscii = (s: string) => s.replace(/[０-９]/g, (ch) => Z2A[ch] ?? ch);

