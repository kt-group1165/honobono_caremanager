/**
 * 氏名カナを伝送用の半角カナへ。ひらがなはカタカナに寄せ、漢字等は落とす。
 * 姓名間の空白は呼び出し側で扱う (ほのぼのは詰めて出す)。
 */
export function toDensouKana(input: string | null | undefined): string {
  if (!input) return "";
  let out = "";
  for (const ch of input) {
    const code = ch.codePointAt(0)!;
    // ひらがな → カタカナ
    const c = code >= 0x3041 && code <= 0x3096 ? String.fromCodePoint(code + 0x60) : ch;
    if (ZEN_TO_HAN[c] !== undefined) {
      out += ZEN_TO_HAN[c];
      continue;
    }
    if (code >= 0xff10 && code <= 0xff5a) {
      out += String.fromCharCode(code - 0xfee0); // 全角英数字 → 半角
      continue;
    }
    if ((code >= 0x20 && code <= 0x7e) || (code >= 0xff61 && code <= 0xff9f)) {
      out += ch; // 既に半角 (ASCII / 半角カナ)
      continue;
    }
    // 漢字等は落とす (カナ項目なので)
  }
  return out;
}
