/**
 * 障害福祉サービスの地域区分単価。
 *
 * ⚠ 介護保険の単価 (offices.unit_price / area_category) をそのまま使ってはいけない。
 *   介護と障害は「人件費割合」が違うため、同じ級地でも単価が変わる。
 *     介護 訪問介護 (人件費割合 70%) 7級地 = 10 × (1 + 0.03 × 0.70) = 10.21
 *     障害 訪問系   (人件費割合 60%) 7級地 = 10 × (1 + 0.03 × 0.60) = 10.18
 *
 * 実伝送 3 事業所で検証済 (2026-07-31):
 *   市原市 (5級地) 五井 = 10.60 / 茂原市 (6級地) = 10.36 / 大網白里市 (7級地) = 10.18
 *   いずれも 10 × (1 + 上乗せ率 × 0.60) と一致した。
 *
 * 単価は「事業所の所在地」の級地で決まる (利用者の市町村ではない)。
 * 大網の伝送では 6 市町村ぶんの明細が全て 10.18 で出ており、これを裏付けている。
 */

/** 級地ごとの上乗せ率 (障害・介護で共通) */
const AREA_SURCHARGE: Record<string, number> = {
  "1級地": 0.20,
  "2級地": 0.16,
  "3級地": 0.15,
  "4級地": 0.12,
  "5級地": 0.10,
  "6級地": 0.06,
  "7級地": 0.03,
  その他: 0,
};

/**
 * 障害福祉 訪問系サービス (居宅介護・重度訪問介護・同行援護・行動援護) の人件費割合。
 * 実伝送から 60% と確認。他のサービス種別 (生活介護・施設入所等) は割合が異なるので、
 * 訪問系以外を扱うようになったら種別ごとに分ける。
 */
const HOMON_JINKENHI_RATIO = 0.6;

/** 障害 訪問系の地域区分単価 (円)。未知の級地は 10.00 (その他扱い) */
export function getShogaiHomonUnitPrice(areaCategory: string | null | undefined): number {
  const surcharge = AREA_SURCHARGE[(areaCategory ?? "その他").trim()] ?? 0;
  // 0.01 円単位で丸める (10 × (1 + 0.03 × 0.6) = 10.18)
  return Math.round(10 * (1 + surcharge * HOMON_JINKENHI_RATIO) * 100) / 100;
}

/** 級地一覧 (設定画面の選択肢用) */
export const SHOGAI_AREA_CATEGORIES = Object.keys(AREA_SURCHARGE);
