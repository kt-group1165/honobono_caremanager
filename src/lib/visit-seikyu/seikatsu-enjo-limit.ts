/**
 * 訪問介護 生活援助中心型の回数上限 (届出基準) チェック
 *
 * 制度:
 *   区分支給限度基準額の範囲内であっても、厚生労働大臣が定める回数「以上」の
 *   訪問介護 (生活援助中心型) を居宅サービス計画 (ケアプラン) に位置付ける場合、
 *   ケアマネジャーは当該ケアプランを市町村へ届け出なければならない
 *   (指定居宅介護支援等の事業の人員及び運営に関する基準 (平成11年厚生省令第38号)
 *    第13条第18号の3。平成30年10月1日施行)。
 *
 * 基準回数 (1月あたり) の根拠 = 「厚生労働大臣が定める回数及び訪問介護」
 * (平成30年厚生労働省告示第218号。平成30年5月2日公布・同年10月1日適用):
 *   要介護1 = 27回 / 要介護2 = 34回 / 要介護3 = 43回 / 要介護4 = 38回 / 要介護5 = 31回
 *   - 「全国平均利用回数 + 2標準偏差 (2SD)」を基に設定
 *     (老振発0510第1号 平成30年5月10日 厚生労働省老健局振興課長通知)
 *   - 2026-07-11 に厚労省法令等データベース (dataId=82ab6417) の告示原文で確認。
 *     令和6年度介護報酬改定 (令和6年厚労省告示第86号) での改正は無く上記値が現行。
 *     要支援 (予防給付) は総合事業移行済みで対象外、届出義務は要介護1〜5のみ。
 *
 * 判定対象 (= 「生活援助中心型」):
 *   サービスコード表 (kaigo_service_codes, service_category=11) のうち、
 *   サービス名が「生活援助N…」(117211 生活援助２ 等) または「生活N・…」
 *   (117857 生活２・Ⅳ / 118001 生活２・Ⅰ 等の特定事業所加算区分合成コード) の系統。
 *   夜朝 (・夜)・深夜 (・深)・2人 (・２人)・虐防・業未 の合成バリエーションも
 *   名称先頭が同じため対象に含まれる。
 *   「身体介護に引き続き生活援助」(身体N生活M / 身N生M・Ⅳ 等) は
 *   生活援助中心型ではない (身体介護中心型の算定) ため対象外 — 名称が
 *   「身」で始まるので下の prefix 判定で自然に除外される。
 */

import { toHankakuDigits } from "@/lib/service-name-normalize";

/** 届出基準回数 (1月あたり)。key = 要介護度 (1〜5) */
export const SEIKATSU_ENJO_KIJUN_KAISU: Record<1 | 2 | 3 | 4 | 5, number> = {
  1: 27,
  2: 34,
  3: 43,
  4: 38,
  5: 31,
};

/**
 * 認定の要介護度文字列 → 届出基準回数。
 * 「要介護３」「要介護3」等の全半角ゆれを吸収する。
 * 要介護1〜5 以外 (要支援・事業対象者・申請中・null 等) は null = 判定対象外
 * (認定が未確定の利用者はチェックをスキップする)。
 */
export function seikatsuEnjoKijunForCareLevel(
  careLevel: string | null | undefined,
): { level: 1 | 2 | 3 | 4 | 5; limit: number } | null {
  if (!careLevel) return null;
  const m = /要介護\s*([1-5])/.exec(toHankakuDigits(careLevel));
  if (!m) return null;
  const level = Number(m[1]) as 1 | 2 | 3 | 4 | 5;
  return { level, limit: SEIKATSU_ENJO_KIJUN_KAISU[level] };
}

/**
 * サービス名が「生活援助中心型」か。
 * - 「生活援助2」「生活援助３・２人・夜」「生活援助2・虐防・業未」等 → true
 * - 「生活2・Ⅳ」「生活３・虐防・Ⅰ」等 (特定事業所加算区分の合成コード) → true
 * - 「身体1生活1」「身５生２・Ⅳ」等 (身体＋生活の複合 = 身体介護中心型) → false
 * - 「生活機能向上連携加算」等 (数字が続かない) → false
 */
export function isSeikatsuEnjoChushin(serviceType: string): boolean {
  const n = toHankakuDigits(serviceType.trim());
  return /^生活(援助)?[0-9]/.test(n);
}
